# -*- coding: utf-8 -*-
"""把 mods 里的流体贴图（可选：乘上游戏导出的颜色）烘成图标，写进 fluids.db 的 fluid_icon 表。

用法：
    python tools/build_fluid_icons.py <mods 目录> [--db <fluids.db>] [--colors <colors.tsv>]
                                     [--size 64] [--dry]

- 贴图来源：所有 jar 里 `assets/<modid>/textures/blocks/fluids/*.png`
  匹配顺序（都按小写比对）：`fluid.<名>` > `<名>.still` > `<名>` > `fluid.<名>.still`
  > `fluid.molten.autogenerated`（molten.* 用）> `fluid.autogenerated`（GT 的通用灰度贴图）
- 颜色：`--colors` 是游戏里 `/aemobile dumpcolors` 导出的 `<流体名>\t<RRGGBB>` 表
  - 有颜色：直接把颜色乘进像素（tint=0），App 直接显示这张彩色图
  - 没颜色：原图入库（tint=1），App 用服务端 NBT 里的 Color 现染——灰度贴图也能正确上色
- 动画贴图（16×N 的竖条）只取第一帧；统一 NEAREST 缩放到 `--size`（默认 64）

为什么要烘颜色：GT 绝大多数流体共用 `fluid.autogenerated.png` 这张**灰度**贴图，
颜色来自 `Fluid.getColor()`（= 材料 RGB）。不乘颜色，1286 条流体里有一千多条是灰的。
"""
import io
import os
import re
import sqlite3
import sys
import zipfile

# GT 的通用灰度贴图：绝大多数材料流体都用它 + 材料色染色
FALLBACK_TEX = ('fluid.molten.autogenerated', 'fluid.autogenerated')

# 流体名里表示状态的前缀/后缀，匹配贴图时要能剥掉
_PREFIX = re.compile(r'^(molten|plasma|liquid|gas|fluid)[._]', re.I)
_SUFFIX = re.compile(r'\.(molten|plasma)$', re.I)


def load_textures(mods_dir):
    """扫所有 jar，返回 {小写贴图名: (jar 路径, 条目名)}；后扫到的覆盖前面的（附属模组优先）。"""
    out = {}
    if not os.path.isdir(mods_dir):
        raise SystemExit('找不到 mods 目录：%s' % mods_dir)
    for jar in sorted(os.listdir(mods_dir)):
        if not jar.lower().endswith('.jar'):
            continue
        path = os.path.join(mods_dir, jar)
        try:
            z = zipfile.ZipFile(path)
        except Exception:
            continue
        for name in z.namelist():
            if '/textures/blocks/' not in name or not name.lower().endswith('.png'):
                continue
            if 'fluid' not in name.lower():
                continue
            out[name.rsplit('/', 1)[-1][:-4].lower()] = (path, name)
    return out


def texture_keys(fluid):
    """流体名 → 按优先级排好的候选贴图名（小写，不带 .png）"""
    n = fluid.lower()
    bases = [n]
    m = _SUFFIX.search(n)
    if m:                                   # aluminum.molten → aluminum
        bases.append(_SUFFIX.sub('', n))
    stripped = _PREFIX.sub('', n)           # molten.steel → steel
    if stripped != n:
        bases.append(stripped)
    bases.append(n.replace('.', '_'))
    bases.append(stripped.replace(' ', '_'))
    bases.append(n.replace(' ', '_'))

    keys = []
    for b in bases:
        keys += ['fluid.' + b, b + '.still', b, 'fluid.' + b + '.still']
    keys += list(FALLBACK_TEX)
    return keys


def load_colors(path):
    """`<流体名>\t<RRGGBB>`；也容忍 `#` 注释、空格分隔、以及 `fluid<TAB>名<TAB>hex` 这种带类型列的行"""
    colors = {}
    if not path:
        return colors
    if not os.path.isfile(path):
        raise SystemExit('找不到颜色表：%s' % path)
    with io.open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.replace('\t', ' ').split()
            if len(parts) >= 3 and parts[0].lower() in ('fluid', 'aspect'):
                parts = parts[1:]
            if len(parts) < 2:
                continue
            try:
                colors[parts[0].lower()] = int(parts[1], 16) & 0xFFFFFF
            except ValueError:
                continue
    return colors


def load_atlas(atlas_dir):
    """读 `/aemobile dump fluids` 导出的图集快照：返回 (PIL 图, {流体名: (x,y,w,h)})，没有就返回 None。

    这是**首选**来源——图集里就是游戏里真正画出来的那张图（GT 的熔融金属/水/岩浆颜色
    并不在 Fluid.getColor() 里，靠颜色算会算错）。
    """
    if not atlas_dir:
        return None
    raw = os.path.join(atlas_dir, 'atlas.raw')
    tsv = os.path.join(atlas_dir, 'fluid-atlas.tsv')
    if not (os.path.isfile(raw) and os.path.isfile(tsv)):
        return None
    from PIL import Image

    w = h = 0
    rects = {}
    with io.open(tsv, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line:
                continue
            parts = line.split('\t')
            if parts[0] == '# atlas':
                w, h = int(parts[1]), int(parts[2])
            elif line.startswith('#'):
                continue
            elif len(parts) >= 5:
                rects[parts[0].lower()] = (int(parts[1]), int(parts[2]), int(parts[3]), int(parts[4]))
    if w <= 0 or h <= 0:
        return None
    size = os.path.getsize(raw)
    if size != w * h * 4:
        raise SystemExit('atlas.raw 大小对不上：%d != %dx%dx4（重新跑 /aemobile dump fluids）' % (size, w, h))
    if size > 800 * 1024 * 1024:
        raise SystemExit('图集太大（%dMB），先把 --atlas-dir 关掉用 jar 贴图' % (size // 1024 // 1024))
    with io.open(raw, 'rb') as f:
        data = f.read()
    im = Image.frombytes('RGBA', (w, h), data)
    r, g, b, a = im.split()
    im = Image.merge('RGBA', (b, g, r, a))        # GL 给的是 BGRA
    im = im.transpose(Image.FLIP_TOP_BOTTOM)      # GL 行序从下往上
    print('图集 %dx%d，记了 %d 个流体图标位置' % (w, h, len(rects)))
    return im, rects


def bake(png_bytes, color, size):
    """取第一帧 → 乘颜色 → NEAREST 放大。返回 (PNG 字节, 是否原样保留)。"""
    from PIL import Image
    im = Image.open(io.BytesIO(png_bytes)).convert('RGBA')
    if im.height > im.width:                     # 动画竖条，只取第一帧
        im = im.crop((0, 0, im.width, im.width))
    if color is not None:
        r, g, b = (color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF
        # 逐通道乘算：alpha 保留，RGB 按颜色缩放（和游戏里 GL 的 tint 一致）
        px = im.load()
        for y in range(im.height):
            for x in range(im.width):
                pr, pg, pb, pa = px[x, y]
                if pa:
                    px[x, y] = (pr * r // 255, pg * g // 255, pb * b // 255, pa)
    if im.width != size:
        im = im.resize((size, size), Image.NEAREST)
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return buf.getvalue()


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return
    mods_dir = sys.argv[1]
    db_path = 'AEMobileApp/assets/fluids.db'
    colors_path = None
    atlas_dir = None
    size = 64
    dry = '--dry' in sys.argv
    argv = sys.argv[2:]
    for i, a in enumerate(argv):
        if a == '--db' and i + 1 < len(argv):
            db_path = argv[i + 1]
        elif a == '--colors' and i + 1 < len(argv):
            colors_path = argv[i + 1]
        elif a == '--atlas-dir' and i + 1 < len(argv):
            atlas_dir = argv[i + 1]
        elif a == '--size' and i + 1 < len(argv):
            size = int(argv[i + 1])

    if not os.path.isfile(db_path):
        raise SystemExit('找不到库：%s（先跑 build_fluid_names.py，或 --db 指定）' % db_path)

    tex = load_textures(mods_dir)
    colors = load_colors(colors_path)
    print('贴图 %d 张（%s），颜色 %d 条（%s）'
          % (len(tex), mods_dir, len(colors), colors_path or '未提供 → 灰度图交给 App 现染'))

    conn = sqlite3.connect(db_path)
    # 名字来源要取并集：fluid_container 只有「有容器」的流体（1286），
    # fluid_name 是 GT 汉化里的全部材料（1512），图集里还有 addon 自己的流体。
    # 只按 fluid_container 建，像 densesupercriticalsteam（超临界致密蒸汽）这种就没有图标了。
    names = []
    seen = set()
    core = set()
    for sql in ('select distinct fluid_name from fluid_container',
                'select fluid from fluid_name'):
        try:
            for (n,) in conn.execute(sql):
                if n and n.lower() not in seen:
                    seen.add(n.lower())
                    names.append(n)
                    if 'fluid_container' in sql:
                        core.add(n.lower())
        except sqlite3.OperationalError:
            pass
    print('库里 %d 条流体' % len(names))

    # jar 要缓存句柄：每条流体都重新开一次 100MB 的 gregtech.jar，1286 条能把磁盘读穿
    jars = {}
    raw_cache = {}
    baked_cache = {}

    def read_tex(key):
        if key not in raw_cache:
            jar, entry = tex[key]
            z = jars.get(jar)
            if z is None:
                z = jars[jar] = zipfile.ZipFile(jar)
            raw_cache[key] = z.read(entry)
        return raw_cache[key]

    rows = []
    missing = []
    used_fallback = 0
    baked = 0
    from_atlas = 0

    # 首选：游戏导出的图集快照（就是游戏里真正画出来的那张图）
    atlas = load_atlas(atlas_dir)
    atlas_img, atlas_rects = atlas if atlas else (None, {})
    # 图集里出现、但库里两条名字表都没有的（addon 注册的流体）也补进来
    for k in atlas_rects:
        if k not in seen:
            seen.add(k)
            names.append(k)
        core.add(k)

    def from_atlas_png(fluid):
        from PIL import Image
        box = atlas_rects[fluid.lower()]
        im = atlas_img.crop((box[0], box[1], box[0] + box[2], box[1] + box[3]))
        if im.width != size:
            im = im.resize((size, size), Image.NEAREST)
        buf = io.BytesIO()
        im.save(buf, 'PNG', optimize=True)
        return buf.getvalue()

    for fluid in names:
        if fluid.lower() in atlas_rects:
            ck = ('@atlas', fluid.lower())
            if ck not in baked_cache:
                baked_cache[ck] = from_atlas_png(fluid)
            rows.append((fluid.lower(), baked_cache[ck], 0))
            from_atlas += 1
            continue
        hit = None
        for key in texture_keys(fluid):
            if key in tex:
                hit = key
                break
        if hit is None:
            missing.append(fluid)
            continue
        if hit in FALLBACK_TEX:
            # 只在 fluid_name 里出现、图集里也没有的（多半是没注册成流体的材料名）：
            # 给一张通用灰图反而误导，不如留空让 App 画纯色块
            if fluid.lower() not in core:
                continue
            used_fallback += 1
        color = colors.get(fluid.lower())
        if color is not None:
            baked += 1
        ck = (hit, color)
        if ck not in baked_cache:
            baked_cache[ck] = bake(read_tex(hit), color, size)
        rows.append((fluid.lower(), baked_cache[ck], 0 if color is not None else 1))

    for z in jars.values():
        z.close()

    print('有图 %d 条（图集 %d 条，jar 兜底 %d 条其中通用灰度贴图 %d 条），烘了颜色 %d 条，缺图 %d 条'
          % (len(rows), from_atlas, len(rows) - from_atlas, used_fallback, baked, len(missing)))
    if missing[:8]:
        print('缺图示例：' + '、'.join(missing[:8]))
    if dry:
        print('（dry-run，未写库）')
        return

    conn.execute('PRAGMA synchronous=OFF')
    conn.execute('drop table if exists fluid_icon')
    conn.execute('create table fluid_icon (fluid text primary key, icon blob, tint integer)')
    conn.executemany('insert into fluid_icon (fluid, icon, tint) values (?,?,?)', rows)
    conn.commit()
    n = conn.execute('select count(*) from fluid_icon').fetchone()[0]
    ok = conn.execute('pragma integrity_check').fetchone()[0]
    conn.close()
    if ok != 'ok':
        raise SystemExit('integrity_check 失败：%s' % ok)
    print('fluid_icon %d 条 → %s（%dKB）'
          % (n, db_path, os.path.getsize(db_path) // 1024))


if __name__ == '__main__':
    main()
